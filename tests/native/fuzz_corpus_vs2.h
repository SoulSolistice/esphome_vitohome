// Seed corpus for the ParserVS2 fuzz target (fuzz_parser_vs2.cpp).
//
// These are the inputs the coverage-guided fuzzer STARTS from, and -- because
// the deterministic replay runner walks the same list -- they double as the
// permanent regression corpus that CI executes on every push. Anything the
// fuzzer ever finds should be minimised and added here, which is what turns a
// one-off campaign into a gate.
//
// They live in a header rather than as files in a corpus directory on purpose.
// Committed binary blobs are unreviewable in a diff, and the repository's
// pre-commit hooks (trailing-whitespace, end-of-file-fixer, mixed-line-ending)
// are text-typed -- a blob that happened to be all-printable would be
// rewritten in place and silently stop being the byte sequence it was added
// for. Bytes plus a stated reason, in the same idiom as fixture_vectors.h, is
// both reviewable and stable. fuzz.sh materialises them into a directory for
// libFuzzer at campaign start.
//
// VS2 frame layout, for reading the arrays below:
//
//   0x41  <len>  <type>  <fc|id<<5>  <addr_hi>  <addr_lo>  <payload_len>  <payload...>  <cs>
//
// <len> counts every byte from itself to the last payload byte (5 + payload),
// and <cs> is their 8-bit sum. Frames whose (fc, type) pair carries no inline
// payload -- READ+REQUEST and WRITE+RESPONSE -- skip the payload entirely, and
// their <payload_len> byte is then unvalidated by the parser, which is why
// several seeds below probe exactly that.

// 0x5525 outside temperature, 2-byte READ RESPONSE -- the ordinary case, straight off hardware
inline constexpr uint8_t kSeed_hw_read_resp_2b[] = {
    0x41, 0x07, 0x01, 0x01, 0x55, 0x25, 0x02, 0x02, 0x01, 0x88,
};

// 0x08E0 part number, 7 ASCII payload bytes, also from the capture
inline constexpr uint8_t kSeed_hw_read_resp_7b[] = {
    0x41, 0x0C, 0x01, 0x01, 0x08, 0xE0, 0x07, 0x35, 0x34, 0x36, 0x34, 0x37, 0x39, 0x33, 0x73,
};

// payload-length 0 on a payload-bearing type: the historic OOB write (THIRD_PARTY.md #12)
inline constexpr uint8_t kSeed_zero_payload_resp[] = {
    0x41, 0x05, 0x01, 0x01, 0x08, 0x00, 0x00, 0x0F,
};

// WRITE+RESPONSE skips to CHECKSUM: data() is nullptr by design, dataLength() is 1
inline constexpr uint8_t kSeed_write_ack[] = {
    0x41, 0x05, 0x01, 0x02, 0x23, 0x23, 0x01, 0x4F,
};

// the same null-data frame claiming the largest dataLength() the wire can express
