// PacketType ERROR: completes at the parser, and the engine routes it to onError (#9)
inline constexpr uint8_t kSeed_error_frame[] = {
    0x41, 0x07, 0x03, 0x01, 0x08, 0x00, 0x02, 0x01, 0x01, 0x17,
};

// function code RPC -- the third accepted value, otherwise untravelled by the fixtures
inline constexpr uint8_t kSeed_rpc_resp[] = {
    0x41, 0x07, 0x01, 0x07, 0xF0, 0x00, 0x02, 0xAA, 0xBB, 0x66,
};

// message id in the top 3 bits of the fc byte, which functionCode() masks off
inline constexpr uint8_t kSeed_ident_bits_set[] = {
    0x41, 0x07, 0x01, 0xE1, 0x55, 0x25, 0x02, 0x02, 0x01, 0x68,
};

// two frames back to back in one read: the parser must complete twice
inline constexpr uint8_t kSeed_two_frames[] = {
    0x41, 0x07, 0x01, 0x01, 0x55, 0x25, 0x02, 0x02, 0x01, 0x88,
    0x41, 0x07, 0x01, 0x01, 0x08, 0x10, 0x02, 0xDC, 0x00, 0xFF,
};

// resync: leading noise including a false start byte and a short length, then a good frame
