#pragma once
#include <cstddef>
#include <cstdint>

// Seed corpus for the GWG session fuzz target (fuzz_gwg_session.cpp), in that
// file's input layout: the switches byte, the operation count, five bytes per
// operation, then the device's script. Same contract as fuzz_corpus_vs2.h:
// seeds for a campaign, the regression corpus for CI.

// one read on an ENQ
inline constexpr uint8_t kGSeed_physical_read[] = {
    0x00, 0x00, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// a second read sent in the burst window
inline constexpr uint8_t kGSeed_burst_two_reads[] = {
    0x00, 0x01, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x00, 0x56, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A, 0x00, 0x2B,
};

// a burst-sent read unanswered, retried on the next ENQ
inline constexpr uint8_t kGSeed_burst_retry[] = {
    0x00, 0x02, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x00, 0x56, 0x00, 0x00, 0x00, 0x00,
    0x57, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A, 0x9E, 0x00, 0x05, 0x00, 0x2B, 0x00, 0x2C,
};

// burst-sent reads that keep the 0x01
inline constexpr uint8_t kGSeed_burst_old_layout[] = {
    0x01, 0x01, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x00, 0x56, 0x00,
    0x00, 0x00, 0x05, 0x00, 0x2A, 0x9E, 0x00, 0x05, 0x00, 0x2B,
};

// an EEPROM read of two addresses, both pairs valid
inline constexpr uint8_t kGSeed_eeprom_run[] = {
    0x00, 0x00, 0x02, 0x00, 0x16, 0x01, 0x00, 0x00, 0x05, 0x01, 0xD7, 0x28, 0x01, 0xE1, 0x1E,
};

// a pair that does not sum to 0xFF
inline constexpr uint8_t kGSeed_eeprom_bad_pair[] = {
    0x00, 0x00, 0x02, 0x00, 0x16, 0x00, 0x00, 0x00, 0x05, 0x01, 0x12, 0x34,
};

// FF FF, an address not in use
inline constexpr uint8_t kGSeed_eeprom_unserved[] = {
    0x00, 0x00, 0x02, 0x00, 0x50, 0x00, 0x00, 0x00, 0x05, 0x01, 0xFF, 0xFF,
};

// an EEPROM write of one cell, acked 00
inline constexpr uint8_t kGSeed_eeprom_write[] = {
    0x00, 0x00, 0x0A, 0x00, 0x16, 0x00, 0x28, 0x00, 0x05, 0x00, 0x00,
};

// an EEPROM write of two bytes, refused
inline constexpr uint8_t kGSeed_eeprom_write_two[] = {
    0x00, 0x01, 0x0A, 0x00, 0x16, 0x01, 0x28, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// a KMBUS write, refused, then a read
inline constexpr uint8_t kGSeed_kmbus_write[] = {
    0x00, 0x01, 0x0E, 0x00, 0x20, 0x00, 0x01, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// a physical write with the EOT before the payload
inline constexpr uint8_t kGSeed_eot_first_write[] = {
    0x02, 0x00, 0x08, 0x00, 0x21, 0x01, 0x10, 0x00, 0x05, 0x00, 0x00,
};

// a 30 ms ENQ-to-send delay
inline constexpr uint8_t kGSeed_enq_delay_30[] = {
    0x14, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x05, 0x83, 0x00, 0x2A,
};

// a byte arriving while the ENQ is held
inline constexpr uint8_t kGSeed_enq_delay_stray[] = {
    0x14, 0x00, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x05, 0x81, 0x00, 0x05, 0x82, 0x00, 0x2A,
};

// the largest delay, then a burst read
inline constexpr uint8_t kGSeed_enq_delay_max[] = {
    0x1C, 0x01, 0x00, 0x00, 0x16, 0x00, 0x00, 0x00, 0x00, 0x17, 0x00, 0x00, 0x00, 0x05, 0x8A, 0x00, 0x2A, 0x00, 0x2B,
};

// an answer 300 ms late
inline constexpr uint8_t kGSeed_late_answer[] = {
    0x00, 0x00, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0x9E, 0x00, 0x2A,
};

// a 2000 ms deadline and a 720 ms answer
inline constexpr uint8_t kGSeed_long_deadline[] = {
    0xE0, 0x00, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0xC8, 0x00, 0x2A,
};

// a 50 ms deadline and a 60 ms answer
inline constexpr uint8_t kGSeed_short_deadline[] = {
    0x40, 0x00, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x05, 0x86, 0x00, 0x2A,
};

// a 69-byte read, refused, then a read
inline constexpr uint8_t kGSeed_read_too_long[] = {
    0x00, 0x01, 0x00, 0x00, 0x55, 0xC5, 0x00, 0x00, 0x00, 0x56, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// an EEPROM run past 0xFF, refused
inline constexpr uint8_t kGSeed_eeprom_past_ff[] = {
    0x00, 0x01, 0x02, 0x00, 0xFE, 0x83, 0x00, 0x00, 0x00, 0x56, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// a 16-bit address
inline constexpr uint8_t kGSeed_high_address[] = {
    0x00, 0x00, 0x10, 0x12, 0x34, 0x00, 0x00, 0x00, 0x05, 0x00, 0x2A,
};

// two reads and no ENQ ever
inline constexpr uint8_t kGSeed_silent_device[] = {
    0x00, 0x01, 0x00, 0x00, 0x55, 0x00, 0x00, 0x00, 0x00, 0x56, 0x00, 0x00,
};

// two bytes for a one-byte read: a TIMEOUT whose report holds both
inline constexpr uint8_t kGSeed_found_overlong_answer[] = {
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0A, 0x05, 0x00, 0x00,
};

// six operations across the modes
inline constexpr uint8_t kGSeed_six_mixed[] = {
    0x00, 0x05, 0x00, 0x00, 0x55, 0x00, 0x00, 0x01, 0x00, 0x10, 0x00, 0x00, 0x02, 0x00, 0x16, 0x00, 0x00,
    0x05, 0x00, 0x03, 0x00, 0x00, 0x0D, 0x00, 0x03, 0x00, 0x07, 0x07, 0x00, 0x40, 0x00, 0x00, 0x00, 0x05,
    0x00, 0x2A, 0x00, 0x2B, 0x01, 0xD7, 0x28, 0x00, 0x2C, 0x00, 0x00, 0x9E, 0x00, 0x05, 0x00, 0x2D,
};

